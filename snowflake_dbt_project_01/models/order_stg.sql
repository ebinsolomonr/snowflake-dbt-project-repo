select
    ORDERID,
    ORDERDATE,
    CUSTOMERID,
    EMPLOYEEID,
    STOREID,
    STATUS AS STATUSCD,
    CASE 
        WHEN STATUS = '01' THEN 'INPROGRESS'
        WHEN STATUS = '02' THEN 'COMPLETED'
        WHEN STATUS = '03' THEN 'CANCELLED'
        ELSE NULL 
    END AS STATUSDESC,
    UPDATED_AT
from DB1.L1_LANDING.ORDERS